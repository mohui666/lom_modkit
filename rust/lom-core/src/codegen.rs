fn splitlines(raw: &str) -> Vec<String> {
    let r = raw.replace("\r\n", "\n").replace(
        [
            '\r', '\u{b}', '\u{c}', '\u{1c}', '\u{1d}', '\u{1e}', '\u{85}', '\u{2028}', '\u{2029}',
        ],
        "\n",
    );
    let mut parts = r.split('\n').map(str::to_owned).collect::<Vec<_>>();
    if r.is_empty() || r.ends_with('\n') {
        parts.pop();
    }
    parts
}
