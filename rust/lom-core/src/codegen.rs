fn story_to_lua_impl(
    story: &Value,
    mod_info: Option<&Value>,
    source: Option<&str>,
    content_root: Option<&Path>,
    previous_big_pictures: bool,
    previous_visual_calls: bool,
    previous_stat_sets: bool,
    previous_shock_wait: bool,
) -> Result<String> {
    let default_root = crate::content::default_repository_root();
    let root = content_root.unwrap_or(&default_root);
    let empty = json!({});
    let info = mod_info.unwrap_or(&empty);
    let nodes = arr(story, "nodes");
    let id = s(story, "id");
    let fallback = format!("story/{id}.json");
    let src = source.filter(|x| !x.is_empty()).unwrap_or(&fallback);
    if let Some(imported) = crate::vanilla_import::parse(story)? {
        return imported_story_to_lua(story, info, src, root, &imported, previous_shock_wait);
    }
    if let Some(patch) = crate::vanilla_patch::parse(story)? {
        let edits: Vec<_> = patch
            .edits
            .iter()
            .enumerate()
            .map(|(index, edit)| {
                let prefix = (!s(info,"id").is_empty()).then(|| format!("MOD_{}_{}_patch_{index}",s(info,"id"),id));
                json!({
                    "find":edit.find,"occurrence":edit.occurrence,"replace":edit.replacement_with_prefix(prefix.as_deref())
                })
            })
            .collect();
        return Ok(format!("{GENERATED_MARK}\n-- Source: {src}\nmodflags = modflags or {{}}\nlocal original = mod_load_vanilla_story({}, {})\nreturn original()\n",
            lua_str(&patch.target), lua_str(&serde_json::to_string(&edits)?)));
    }
    let mood = b(story, "mood", false);
    // Explicit switches follow runtime control flow, including loops/branches.
    // Let the existing Host ShowMood patch enforce disabled state; unconditional
    // legacy hide calls would otherwise erase an explicitly enabled bubble.
    let dynamic_mood = crate::parallel::story_actions(story).any(|(_, n)| s(n, "type") == "mood");
    let narrative_layout = nodes
        .iter()
        .any(|n| ["narrative", "center"].contains(&s(n, "mode")) && s(n, "text_align") == "left");
    let character_layout = crate::parallel::story_actions(story)
        .any(|(_, node)| node["type"] == "offset" && (has(node, "absolute") || has(node, "scale")));
    let managed_effects = crate::parallel::story_actions(story).any(|(_, node)| {
        node["type"] == "effect"
            && crate::validate::EFFECT_CONTROL_FIELDS
                .iter()
                .any(|key| has(node, key))
    });
    let mut lines = vec![
        GENERATED_MARK.to_owned(),
        format!("-- Source: {src} (id={id}, title={})", s(story, "title")),
    ];
    if mod_info.is_some() && info.as_object().is_some_and(|v| !v.is_empty()) {
        lines.push(format!(
            "-- Mod: {} ({}) v{} by {}",
            s(info, "id"),
            s(info, "name"),
            s(info, "version"),
            s(info, "author")
        ));
    }
    lines.extend([
        "".into(),
        "-- mod 内剧情 flag 表（不存档，重进游戏清零）".into(),
        "modflags = modflags or {}".into(),
        format!("mod_set_mood({mood})"),
        "mod_hide_all()".into(),
        "".into(),
        "-- 节点函数前向声明（支持任意 goto / 分支回环）".into(),
        format!(
            "local {}",
            nodes
                .iter()
                .map(|n| format!("node_{}", s(n, "id")))
                .collect::<Vec<_>>()
                .join(", ")
        ),
        "".into(),
    ]);
    if nodes.iter().any(|node| s(node, "type") == "parallel") {
        lines.push(include_str!("../data/parallel.lua").into());
    }
    for (i, node) in nodes.iter().enumerate() {
        let nid = s(node, "id");
        let kind = s(node, "type");
        let next = nodes.get(i + 1).map(|n| s(n, "id")).unwrap_or("");
        let ctx = Context {
            mod_id: s(info, "id"),
            script_id: id,
            mood: mood || dynamic_mood,
            narrative_layout,
            next,
            content_root: root,
            preloaded: false,
            previous_big_pictures,
            previous_visual_calls,
            previous_stat_sets,
            previous_shock_wait,
            character_layout,
            managed_effects,
        };
        lines.extend([
            format!("-- [{nid}] {kind}"),
            format!("node_{nid} = function()"),
            format!(
                "\tif mod_trace_node then mod_trace_node({}, {}) end",
                lua_str(nid),
                lua_str(kind)
            ),
        ]);
        lines.extend(emit(node, &ctx)?);
        if !NO_FLOW.contains(&kind) {
            let target = if node["goto"].is_null() {
                next
            } else {
                s(node, "goto")
            };
            if !target.is_empty() {
                lines.push(format!("\treturn node_{target}()"));
            }
        }
        lines.extend(["end".into(), "".into()]);
    }
    if nodes
        .iter()
        .any(|n| ["combat", "battle"].contains(&s(n, "type")))
    {
        lines.extend([
            "-- 原版战斗返回 Story 后，由 Host 一次性消费已记录的结果目标。".into(),
            format!(
                "local mod_resume_target = mod_gameplay_consume_resume({})",
                lua_str(id)
            ),
            "if mod_resume_target ~= nil and mod_resume_target ~= \"\" then".into(),
        ]);
        for (i, node) in nodes.iter().enumerate() {
            lines.push(format!(
                "\t{} mod_resume_target == {} then return node_{}()",
                if i == 0 { "if" } else { "elseif" },
                q(node, "id"),
                s(node, "id")
            ));
        }
        lines.extend([
            "\telse error(\"Host 返回了未知战斗续接节点: \" .. tostring(mod_resume_target)) end"
                .into(),
            "end".into(),
        ]);
    }
    lines.push(format!("return node_{}()", s(story, "start")));
    Ok(lines.join("\n") + "\n")
}

fn imported_story_to_lua(
    story: &Value,
    info: &Value,
    source: &str,
    root: &Path,
    imported: &crate::vanilla_import::Imported,
    previous_shock_wait: bool,
) -> Result<String> {
    let nodes = arr(story, "nodes");
    if imported.schema == 2 {
        return structured_import_to_lua(story, info, source, root, imported, previous_shock_wait);
    }
    let origins = imported.associations(nodes);
    let mut lua = format!("{GENERATED_MARK}\n-- Source: {source}\nmodflags = modflags or {{}}\nmod_begin_vanilla_import({})\nlocal mod_vanilla_terminal = {{}}\n", q(story,"id"));
    lua.push_str(include_str!("../data/vanilla_import.lua"));
    lua.push('\n');
    if !b(story, "mood", true) {
        lua.push_str("mod_set_mood(false)\n");
    }
    if nodes.iter().any(|node| node["type"] == "parallel") {
        lua.push_str(include_str!("../data/parallel.lua"));
        lua.push('\n');
    }
    let mut start = 0;
    while start < nodes.len() {
        if crate::vanilla_import::Imported::native_raw(origins[start], &nodes[start]) {
            lua.push_str(s(&nodes[start], "code"));
            lua.push('\n');
            start += 1;
            continue;
        }
        let end = (start..nodes.len())
            .find(|&index| {
                crate::vanilla_import::Imported::native_raw(origins[index], &nodes[index])
            })
            .unwrap_or(nodes.len());
        lua.push_str("do\n");
        let mut names: Vec<_> = nodes[start..end]
            .iter()
            .map(|node| format!("node_{}", s(node, "id")))
            .collect();
        if let Some(boundary) = nodes.get(end) {
            names.push(format!("node_{}", s(boundary, "id")));
        }
        lua.push_str(&format!("local {}\n", names.join(", ")));
        if let Some(boundary) = nodes.get(end) {
            lua.push_str(&format!("node_{} = function() end\n", s(boundary, "id")));
        }
        for index in start..end {
            let node = &nodes[index];
            let next = nodes.get(index + 1).map(|node| s(node, "id")).unwrap_or("");
            let original = origins[index]
                .filter(|origin| crate::vanilla_import::Imported::unchanged(origin, node));
            lua.push_str(&format!("node_{} = function()\n\t{}()\n\tmod_vanilla_source_node({})\n\tif mod_trace_node then mod_trace_node({}, {}) end\n",s(node,"id"),if original.is_some() {"__lom_restore_native"} else {"__lom_enter_custom"},q(node,"id"),q(node,"id"),q(node,"type")));
            if let Some(origin) = original {
                lua.push_str(&origin.code);
                lua.push('\n');
            } else {
                let context = Context {
                    mod_id: s(info, "id"),
                    script_id: s(story, "id"),
                    mood: true,
                    narrative_layout: true,
                    next,
                    content_root: root,
                    preloaded: false,
                    previous_big_pictures: false,
                    previous_visual_calls: false,
                    previous_stat_sets: false,
                    previous_shock_wait,
                    character_layout: true,
                    managed_effects: true,
                };
                // Changing only the words keeps the native speaker, dialog,
                // wait options and portrait selected by the surrounding script.
                let text_only = origins[index].is_some_and(|origin| {
                    let mut baseline = crate::vanilla_import::comparable(&origin.node);
                    baseline["text"] = node["text"].clone();
                    node["type"] == "say" && baseline == crate::vanilla_import::comparable(node)
                });
                let lines = if node["type"] == "end" && b(node, "resume_original", false) {
                    let target = crate::vanilla_import::resume_index(story, index);
                    vec![target
                        .map(|next| format!("\treturn node_{}()", s(&nodes[next], "id")))
                        .unwrap_or_else(|| "\treturn".into())]
                } else if text_only {
                    vec![dialogue_line(node, &context)]
                } else {
                    emit(node, &context)?
                };
                lua.push_str(&lines.join("\n"));
                lua.push('\n');
                if matches!(
                    s(node, "type"),
                    "goto_scene" | "death" | "combat" | "battle"
                ) || node["type"] == "end" && !b(node, "resume_original", false)
                {
                    lua.push_str("\tcoroutine.yield(\"__lom_vanilla_import_complete__\")\n");
                    lua.push_str("\treturn mod_vanilla_terminal\n");
                }
            }
            if !NO_FLOW.contains(&s(node, "type")) {
                let target = node["goto"].as_str().unwrap_or(next);
                if !target.is_empty() {
                    lua.push_str(&format!("\treturn node_{target}()\n"));
                }
            }
            lua.push_str("end\n");
        }
        lua.push_str(&format!("if node_{}() == mod_vanilla_terminal then return end\nend\n__lom_restore_native()\nmod_vanilla_source_continue()\n",s(&nodes[start],"id")));
        start = end;
    }
    Ok(lua)
}

fn preview_character_resources(value: &Value, resources: &mut BTreeMap<String, BTreeSet<String>>) {
    let function = &value["function"];
    let method = s(function, "field");
    let arguments = arr(value, "args");
    if value["kind"] == "call"
        && function["kind"] == "member"
        && function["object"]["kind"] == "name"
        && function["object"]["name"] == "characters"
        && ((method == "Get" && arguments.len() == 1)
            || (method == "GetPortrait" && arguments.len() == 2))
        && arguments[0]["kind"] == "literal"
    {
        if let Some(character) = arguments[0]["value"].as_str() {
            let portraits = resources.entry(character.to_owned()).or_default();
            if method == "GetPortrait" && arguments[1]["kind"] == "literal" {
                if let Some(portrait) = arguments[1]["value"].as_str() {
                    portraits.insert(portrait.to_owned());
                }
            }
        }
    }
    match value {
        Value::Array(values) => {
            for value in values {
                preview_character_resources(value, resources);
            }
        }
        Value::Object(fields) => {
            for value in fields.values() {
                preview_character_resources(value, resources);
            }
        }
        _ => {}
    }
}

fn structured_import_to_lua(
    story: &Value,
    info: &Value,
    source: &str,
    root: &Path,
    imported: &crate::vanilla_import::Imported,
    previous_shock_wait: bool,
) -> Result<String> {
    let nodes = arr(story, "nodes");
    let origins = imported.associations(nodes);
    let standalone_preview = info["id"] == "lom_modkit_preview";
    let mut lua=format!("{GENERATED_MARK}\n-- Source: {source}\nmodflags = modflags or {{}}\nmod_begin_vanilla_import({})\nlocal __lom_locals, __lom_nodes = {{}}, {{}}\nlocal __lom_finished, __lom_result = false, nil\n",q(story,"id"));
    lua.push_str(include_str!("../data/vanilla_import.lua"));
    if nodes.iter().any(|n| n["type"] == "parallel") {
        lua.push_str(include_str!("../data/parallel.lua"));
    }
    if standalone_preview {
        let mut resources = BTreeMap::new();
        for (index, node) in nodes.iter().enumerate() {
            match s(node, "type") {
                "native_action" => preview_character_resources(&node["operations"], &mut resources),
                "native_branch" => preview_character_resources(&node["condition"], &mut resources),
                kind => {
                    if let Some(operations) = origins[index]
                        .filter(|origin| {
                            crate::vanilla_import::Imported::unchanged(origin, node)
                                && !(imported.external && kind == "say")
                        })
                        .and_then(|origin| origin.operations.as_ref())
                    {
                        for operation in operations {
                            preview_character_resources(operation, &mut resources);
                        }
                    }
                }
            }
        }
        // A standalone F5 chapter can inherit characters from an earlier chapter.
        // These APIs only add missing resources, retaining any live stage state.
        for (character, portraits) in resources {
            lua.push_str(&format!("{}\n", load(&lua_str(&character))));
            for portrait in portraits {
                lua.push_str(&format!(
                    "{}\n",
                    call(
                        "characters.LoadCharacterPortrait",
                        &[lua_str(&character), lua_str(&portrait)],
                    )
                ));
            }
        }
    }
    let preamble_end = lua.len();
    let mut preview_stage_default = false;
    for (index, node) in nodes.iter().enumerate() {
        let kind = s(node, "type");
        let next = node["goto"]
            .as_str()
            .or_else(|| nodes.get(index + 1).and_then(|n| n["id"].as_str()))
            .unwrap_or("");
        let context = Context {
            mod_id: s(info, "id"),
            script_id: s(story, "id"),
            mood: true,
            narrative_layout: true,
            next,
            content_root: root,
            preloaded: false,
            previous_big_pictures: false,
            previous_visual_calls: false,
            previous_stat_sets: false,
            previous_shock_wait,
            character_layout: true,
            managed_effects: true,
        };
        let original = origins[index]
            .filter(|origin| crate::vanilla_import::Imported::unchanged(origin, node));
        let native = matches!(kind, "native_action" | "native_branch") || original.is_some();
        lua.push_str(&format!("\n__lom_nodes[{}] = function()\n\t{}()\n\tmod_vanilla_source_node({})\n\tif mod_trace_node then mod_trace_node({}, {}) end\n",q(node,"id"),if native {"__lom_restore_native"} else {"__lom_enter_custom"},q(node,"id"),q(node,"id"),q(node,"type")));
        if kind == "native_branch" {
            lua.push_str(&format!(
                "\tif {} then return {} else return {} end\n",
                crate::native_flow::expression(&node["condition"])?,
                q(node, "success"),
                q(node, "failure")
            ));
        } else {
            let mut terminal = false;
            let mut body = if kind == "native_action" {
                let ops = arr(node, "operations");
                terminal = ops.iter().any(|op| op["kind"] == "return");
                crate::native_flow::operations(ops)?
            } else if imported.external && kind == "say" && original.is_some() {
                emit(node, &context)?.join("\n")
            } else if let Some(ops) = original.and_then(|origin| origin.operations.as_ref()) {
                crate::native_flow::operations(ops)?
            } else if kind == "end" && node["resume_original"] == true {
                terminal = true;
                crate::vanilla_import::resume_index(story, index)
                    .map(|i| format!("return {}", q(&nodes[i], "id")))
                    .unwrap_or_else(|| "return nil".into())
            } else {
                terminal = NO_FLOW.contains(&kind);
                let mut body = emit(node, &context)?.join("\n");
                // Token-aware replacement leaves dialogue literals and comments intact.
                let tokens = crate::vanilla_patch::tokens(&body);
                for group in tokens.windows(4).rev() {
                    if group[0].value == "return"
                        && !group[0].string
                        && !group[1].string
                        && group[1].value.starts_with("node_")
                        && group[2].value == "("
                        && group[3].value == ")"
                    {
                        body.replace_range(
                            group[1].start..group[3].end,
                            &lua_str(&group[1].value[5..]),
                        );
                    }
                }
                body
            };
            if standalone_preview {
                let tokens = crate::vanilla_patch::tokens(&body);
                for (index, call) in tokens.windows(4).enumerate().rev() {
                    if !call[0].string
                        && call[0].value == "stage"
                        && call[1].value == "."
                        && !call[2].string
                        && call[2].value == "show"
                        && (index == 0 || ![".", ":"].contains(&tokens[index - 1].value.as_str()))
                        && ["(", "{"].contains(&call[3].value.as_str())
                    {
                        body.replace_range(call[0].start..call[2].end, "__lom_preview_show");
                        preview_stage_default = true;
                    }
                }
            }
            lua.push_str(&body);
            lua.push('\n');
            if !terminal {
                lua.push_str(&format!(
                    "\treturn {}\n",
                    if next.is_empty() {
                        "nil".into()
                    } else {
                        lua_str(next)
                    }
                ));
            }
        }
        lua.push_str("end\n");
    }
    if preview_stage_default {
        // Select the loaded default only when the actual show step runs. A
        // character already on stage or carrying a portrait keeps that state.
        lua.insert_str(preamble_end, "\nlocal function __lom_preview_show(options)\n\tlocal character = options.character\n\tif character ~= nil and options.portrait == nil and not character.State.onScreen and character.State.portrait == nil then\n\t\tlocal portrait = character.Portraits[1]\n\t\tif portrait ~= nil then options.portrait = portrait.name end\n\tend\n\treturn stage.show(options)\nend\n");
    }
    lua.push_str(&format!("\nlocal __lom_current = {}\nwhile __lom_current do\n\tlocal __lom_step = __lom_nodes[__lom_current]\n\tif not __lom_step then error(\"原版步骤去向不存在: \" .. tostring(__lom_current)) end\n\t__lom_current = __lom_step()\n\tmod_vanilla_source_continue()\nend\n__lom_restore_native()\nif __lom_finished then return __lom_result end\n",q(story,"start")));
    Ok(lua)
}

fn scoped_dialogue_line(node: &Value, ctx: &Context<'_>) -> Vec<String> {
    let offscreen = s(node, "mode") == "offscreen";
    let mut out = Vec::new();
    if offscreen {
        let name = s(node, "speaker_name");
        let name = if name.trim().is_empty() {
            "？？？"
        } else {
            name
        };
        out.push(format!(
            "\tlocal __lom_restore_name = mod_dialogue_name({})",
            lua_str(name)
        ));
    }
    if truth(node, "mood_icon") {
        let target = if truth(node, "mood_character") {
            s(node, "mood_character")
        } else {
            s(node, "character")
        };
        out.push(format!(
            "\tlocal __lom_restore_mood = mod_dialogue_mood({}, {})",
            lua_str(target),
            q(node, "mood_icon")
        ));
    }
    out.push(dialogue_line(node, ctx));
    if truth(node, "mood_icon") {
        out.push("\t__lom_restore_mood()".into());
    }
    if offscreen {
        out.push("\t__lom_restore_name()".into());
    }
    out
}
fn dialogue_line(node: &Value, ctx: &Context<'_>) -> String {
    let mod_id = if ctx.mod_id.is_empty() {
        "MOD"
    } else {
        ctx.mod_id
    };
    let key = format!("MOD_{mod_id}_{}_{}", ctx.script_id, s(node, "id"));
    let text = format!("luamanager.GetStoryText({})", lua_str(&key));
    let size = node["font_size"]
        .as_i64()
        .unwrap_or(match s(node, "font_size") {
            "small" => 24,
            "large" => 60,
            _ => 0,
        });
    if size > 0 {
        format!("\tsay(\"{{size={size}}}\" .. {text} .. \"{{/size}}\")")
    } else {
        format!("\tsay({text})")
    }
}
