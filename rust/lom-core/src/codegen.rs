fn emit_dice(node: &Value) -> Result<Vec<String>> {
    let legacy = has(node, "check");
    let meta = &editor_data()["dice_meta"][s(node, "check")];
    let fallback = json!([{"text":sd(&node["options"][0],"text",""),"cond":""}]);
    let bands = if legacy {
        meta["bands"]
            .as_array()
            .filter(|a| !a.is_empty())
            .unwrap_or(fallback.as_array().unwrap())
            .as_slice()
    } else {
        arr(node, "bands")
    };
    let maximum = if legacy {
        n(meta, "max", json!(99))
    } else {
        n(node, "max", json!(99))
    };
    let check_name = if legacy {
        q(node, "check")
    } else {
        lua_str("__lom_mod_custom")
    };
    let mut out = Vec::new();
    if !legacy {
        let thresholds = bands[..bands.len() - 1]
            .iter()
            .map(|b| pystr(&b["upper"]))
            .collect::<Vec<_>>()
            .join(",");
        out.push(call(
            "mod_dice_prepare",
            &[
                maximum.clone(),
                q(node, "header"),
                lua_str(&thresholds),
                n(node, "bonus", json!(0)),
                q(node, "bonus_name"),
                q(node, "bonus_status"),
            ],
        ));
    }
    out.extend([
        "\tsetmenudialog(menudialogs.Dice)".into(),
        format!(
            "\tlocal dice_rand1 = math.random({}{maximum})",
            if legacy { "" } else { "0, " }
        ),
        format!("\tdicemenudialog.SetRandom({maximum}, dice_rand1)"),
        format!("\tlocal dice_result1 = checkpointmanager.Dice({check_name}, dice_rand1)"),
        "\tlocal dice_opts1 = {}".into(),
    ]);
    let texts = arr(&node["options"][0], "band_texts");
    for (i, band) in bands.iter().enumerate() {
        let text = if legacy && texts.len() == bands.len() {
            pystr(&texts[i])
        } else {
            s(band, "text").into()
        }
        .replace('|', "｜");
        let condition = if legacy {
            s(band, "cond").into()
        } else if i + 1 < bands.len() {
            format!("≤ {}", pystr(&band["upper"]))
        } else {
            format!("> {}", pystr(&bands[bands.len() - 2]["upper"]))
        };
        out.push(format!(
            "\tdice_opts1[{}] = {}",
            i + 1,
            lua_str(&format!("{text}|{condition}"))
        ));
    }
    out.extend(["\tdicemenudialog.Setup(dice_result1.ResultCount, dice_result1.Result, dice_result1.Header, dice_result1.Additions)".into(),format!("\trunwait(dicemenudialog.ExecuteRoll(dice_opts1, 1, {check_name}))"),"\tlocal dice_sel1 = dicemenudialog.ResultSelection".into()]);
    if !legacy {
        out.push("\tmod_dice_clear()".into());
    }
    let ranks = band_rank(bands);
    let target = |i: usize| -> &str {
        if !legacy {
            return s(&bands[i], "goto");
        }
        let field = if ranks[i] == 1 {
            "goto_失败"
        } else if ranks[i] == bands.len() && bands.len() >= 3 {
            "goto_大成功"
        } else {
            "goto_成功"
        };
        s(&node["options"][0], field)
    };
    out.push("\tif dice_sel1 == 1 then".into());
    out.push(ret(target(0)));
    for i in 1..bands.len().saturating_sub(1) {
        out.push(format!("\telseif dice_sel1 == {} then", i + 1));
        out.push(ret(target(i)));
    }
    out.extend([
        "\telse".into(),
        ret(target(bands.len() - 1)),
        "\tend".into(),
    ]);
    Ok(out)
}
fn band_rank(bands: &[Value]) -> Vec<usize> {
    let re = regex::Regex::new(r"(<=|>=|<|>|=)\s*(\d+)").unwrap();
    let parsed = bands
        .iter()
        .map(|b| {
            re.captures(s(b, "cond")).map(|c| {
                (
                    c[2].parse::<i64>().unwrap_or(0),
                    [">", ">=", "="].contains(&&c[1]),
                )
            })
        })
        .collect::<Vec<_>>();
    let mut order = (0..bands.len()).collect::<Vec<_>>();
    order.sort_by_key(|i| parsed[*i].unwrap_or((-1, false)));
    let mut ranks = vec![0; bands.len()];
    for (rank, i) in order.into_iter().enumerate() {
        ranks[i] = rank + 1;
    }
    ranks
}
