/// Compile only after validation; warnings retain their position before the generated header.
pub fn compile_story(
    story: &Value,
    mod_info: Option<&Value>,
    source: Option<&str>,
    content_root: Option<&Path>,
) -> Result<String> {
    let warnings = crate::validate::validate_story(story)?;
    let lua = story_to_lua(story, mod_info, source, content_root)?;
    if warnings.is_empty() {
        Ok(lua)
    } else {
        Ok(format!(
            "{}\n{lua}",
            warnings
                .iter()
                .map(|w| format!("-- lomc 警告：{}", w.replace('\n', " ")))
                .collect::<Vec<_>>()
                .join("\n")
        ))
    }
}
