def main() -> int:
    """按文本插入新键，不整份重写文件（避免把四份语言包抖成大 diff）。"""
    for code in ("chs", "cht", "ja", "ko"):
        path = LOCALES / f"{code}.json"
        text = path.read_text(encoding="utf-8")
        existing = json.loads(text)
        pairs = [
            (key, translations[code])
            for key, translations in TEXTS.items()
            if existing.get(key) != translations[code]
        ]
        if not pairs:
            print(f"[{code}] 无需改动（{len(existing)} 个键）")
            continue
        body = text.rstrip()
        if not body.endswith("}"):
            raise SystemExit(f"{path} 结尾不是 JSON 对象，已中止")
        body = body[:-1].rstrip()
        if not body.endswith(","):
            body += ","
        entries = ",\n".join(
            f"  {json.dumps(k, ensure_ascii=False)}: {json.dumps(v, ensure_ascii=False)}"
            for k, v in pairs
        )
        path.write_text(f"{body}\n{entries}\n}}\n", encoding="utf-8")
        reload = json.loads(path.read_text(encoding="utf-8"))
        print(f"[{code}] 写入 {len(pairs)} 个键，共 {len(reload)}")
    print("本轮新增键总数：", len(TEXTS))
    return 0


if __name__ == "__main__":
    sys.exit(main())
