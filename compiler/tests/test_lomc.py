class TestCompileValid(unittest.TestCase):
    def test_header_and_structure(self):
        lua = compile_story(
            linear_story({"id": "n1", "type": "music", "name": "普通_001"}),
            mod_info=MANIFEST,
            source="story/main.json",
        )
        lines = lua.splitlines()
        self.assertEqual(lines[0], "-- Generated by lomc, do not edit")
        self.assertIn("-- Source: story/main.json (id=main, title=测试剧情)", lines[1])
        self.assertIn("-- Mod: testmod (测试 Mod) v0.1.0 by tester", lines[2])
        # 前向声明 + 函数定义 + 顶层入口
        self.assertIn("local node_n1, node_nend", lua)
        self.assertIn("node_n1 = function()", lua)
        self.assertEqual(lines[-1], "return node_n1()")
        # 契约 §4：脚本开头初始化 mod 内 flag 表（在前向声明之前）
        self.assertIn("modflags = modflags or {}", lines)
        self.assertLess(
            lines.index("modflags = modflags or {}"),
            lines.index("local node_n1, node_nend"),
        )
        # 契约 §4：mood 声明（story 顶层 mood 默认 false）紧跟 modflags 行
        self.assertIn("mod_set_mood(false)", lines)
        self.assertEqual(
            lines.index("mod_set_mood(false)"),
            lines.index("modflags = modflags or {}") + 1,
        )
        self.assertIn("mod_hide_all()", lines)
        self.assertEqual(
            lines.index("mod_hide_all()"),
            lines.index("mod_set_mood(false)") + 1,
        )

    def test_implicit_and_explicit_goto(self):
        lua = compile_story(
            linear_story(
                {"id": "n1", "type": "music", "name": "普通_001"},
                {"id": "n2", "type": "focus", "character": "player"},
            )
        )
        # 顺序流：n1 隐式流向 n2
        self.assertIn("\treturn node_n2()", lua)
        # 显式 goto 覆盖顺序流
        lua2 = compile_story(
            linear_story(
                {"id": "n1", "type": "music", "name": "普通_001", "goto": "nend"},
                {"id": "n2", "type": "focus", "character": "player"},
            )
        )
        self.assertIn("\treturn node_nend()", lua2)

    def test_string_escape(self):
        # 转义覆盖改在 music 名称上验（say 文本已不再裸字面量进 Lua，改走已读 key）
        lua = compile_story(
            linear_story(
                {
                    "id": "n1",
                    "type": "music",
                    "name": '反斜杠\\引号"换行\n第二行',
                }
            )
        )
        self.assertIn('luamanager.PlayMusic("反斜杠\\\\引号\\"换行\\n第二行")', lua)

    def test_number_format(self):
        lua = compile_story(
            linear_story(
                {"id": "n1", "type": "stat", "key": "mental", "delta": -5},
                {"id": "n2", "type": "wait", "seconds": 1.5},
                {"id": "n3", "type": "wait", "seconds": 2.0},
            )
        )
        self.assertIn('statmodifymanager.Player("mental", -5, "", 1)', lua)
        self.assertIn("\twait(1.5)", lua)
        self.assertIn("\twait(2)", lua)  # 整数值不带小数点


