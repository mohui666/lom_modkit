class TestNewNodeValidationErrors(unittest.TestCase):
    def test_sound_fadeout_requires_env(self):
        assert_compile_error(
            self,
            linear_story({"id": "n1", "type": "sound", "name": "x", "op": "fadeout"}),
            'op="fadeout" 仅支持 kind="env"',
            "n1",
        )

    def test_cg_rules(self):
        # hide + title 无官方 API
        assert_compile_error(
            self,
            linear_story({"id": "n1", "type": "cg", "action": "hide", "kind": "title"}),
            'action="hide" 不支持 kind="title"',
        )
        # show map 缺 key2
        assert_compile_error(
            self,
            linear_story({"id": "n1", "type": "cg", "action": "show",
                          "kind": "map", "key": "Home"}),
            '必填字段 "key2"',
            "n1",
        )

    def test_item_remove_special(self):
        assert_compile_error(
            self,
            linear_story({"id": "n1", "type": "item", "kind": "special",
                          "item": "4005", "remove": True}),
            "remove 仅支持",
            "n1",
        )

    def test_enemy_value_required(self):
        assert_compile_error(
            self,
            linear_story({"id": "n1", "type": "enemy", "op": "team", "enemy": "400"}),
            '必填字段 "value"',
            "n1",
        )
        # op="id" 不需要 value：通过
        validate_story(
            linear_story({"id": "n1", "type": "enemy", "op": "id", "enemy": "001"})
        )

    def test_battle_skill_key_required(self):
        assert_compile_error(
            self,
            linear_story({"id": "n1", "type": "battle_skill", "op": "set"}),
            '必填字段 "key"',
        )

    def test_time_fields(self):
        assert_compile_error(
            self,
            linear_story({"id": "n1", "type": "time", "op": "set", "year": 1}),
            '必填字段 "month"',
        )
        assert_compile_error(
            self,
            linear_story({"id": "n1", "type": "time", "op": "mission",
                          "year": 0, "month": 0, "stage": 1}),
            '必填字段 "name"',
        )

    def test_panel_key_required(self):
        assert_compile_error(
            self,
            linear_story({"id": "n1", "type": "panel", "panel": "cg"}),
            '必填字段 "key"',
        )

    def test_talent_level(self):
        assert_compile_error(
            self,
            linear_story({"id": "n1", "type": "talent", "talent": "3004", "level": 2}),
            '字段 "level" 必须是1 或 -1',
        )

    def test_official_id_nonempty(self):
        # dice.check / game_flag.flag / branch.flag 只校验非空，不查表
        assert_compile_error(
            self,
            linear_story({"id": "n1", "type": "game_flag", "flag": "", "value": 1}),
            '字段 "flag" 必须是非空字符串',
        )
        # 不在官方清单里的 id 也放行（编辑器侧管清单）
        validate_story(
            linear_story({"id": "n1", "type": "game_flag", "flag": "CUSTOM_ID", "value": 1})
        )

    def test_dice_options(self):
        # 0 项 / 5 项
        for options in (
            [],
            [{"text": str(i), "threshold": 50, "goto_大成功": "nend",
              "goto_成功": "nend", "goto_失败": "nend"} for i in range(5)],
        ):
            assert_compile_error(
                self,
                linear_story({"id": "n1", "type": "dice",
                              "check": "Combat_Result_01", "options": options}),
                "选项数必须在 1~4 之间",
                "n1",
            )
        # 缺 threshold / 缺三向 goto
        assert_compile_error(
            self,
            linear_story({"id": "n1", "type": "dice", "check": "C",
                          "options": [{"text": "x", "goto_大成功": "nend",
                                       "goto_成功": "nend", "goto_失败": "nend"}]}),
            '缺少必填字段 "threshold"',
        )
        assert_compile_error(
            self,
            linear_story({"id": "n1", "type": "dice", "check": "C",
                          "options": [{"text": "x", "threshold": 50,
                                       "goto_大成功": "nend", "goto_成功": "nend"}]}),
            '缺少必填字段 "goto_失败"',
        )
        # 三向 goto 指向不存在节点
        assert_compile_error(
            self,
            linear_story({"id": "n1", "type": "dice", "check": "C",
                          "options": [{"text": "x", "threshold": 50, "goto_大成功": "ghost",
                                       "goto_成功": "nend", "goto_失败": "nend"}]}),
            'goto 指向不存在的节点 "ghost"',
        )

    def test_raw_empty_code(self):
        assert_compile_error(
            self, linear_story({"id": "n1", "type": "raw", "code": "  \n "}),
            '"code" 不能为空',
        )

    def test_no_goto_types_v3(self):
        # dice / goto_scene 也禁止显式 goto（契约 §4）
        assert_compile_error(
            self,
            linear_story({"id": "n1", "type": "goto_scene", "scene": "Free", "goto": "nend"}),
            '不允许显式 "goto"',
            "n1",
        )
        assert_compile_error(
            self,
            linear_story({"id": "n1", "type": "dice", "check": "C", "goto": "nend",
                          "options": [{"text": "x", "threshold": 1, "goto_大成功": "nend",
                                       "goto_成功": "nend", "goto_失败": "nend"}]}),
            '不允许显式 "goto"',
        )


