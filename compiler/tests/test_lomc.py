class TestCli(unittest.TestCase):
    def run_cli(self, *argv):
        # Windows 控制台默认 GBK，子进程输出中文会乱码/解码失败，
        # 统一用 PYTHONIOENCODING 强制 UTF-8
        env = dict(os.environ, PYTHONIOENCODING="utf-8")
        return subprocess.run(
            [sys.executable, "-m", "lomc"] + list(argv),
            cwd=COMPILER_ROOT,
            capture_output=True,
            text=True,
            encoding="utf-8",
            env=env,
        )

    def test_check_ok_and_fail(self):
        with tempfile.TemporaryDirectory() as tmp:
            good = os.path.join(tmp, "good.json")
            with open(good, "w", encoding="utf-8") as f:
                json.dump(linear_story({"id": "n1", "type": "music", "name": "普通_001"}), f)
            r = self.run_cli("check", good)
            self.assertEqual(r.returncode, 0, r.stderr)
            self.assertIn("校验通过", r.stdout)

            bad = os.path.join(tmp, "bad.json")
            with open(bad, "w", encoding="utf-8") as f:
                json.dump(make_story([{"id": "n1", "type": "wat"}, {"id": "n2", "type": "end"}]), f)
            r = self.run_cli("check", bad)
            self.assertEqual(r.returncode, 1)
            self.assertIn("错误", r.stderr)
            self.assertIn("未知节点类型", r.stderr)

    def test_build_and_pack(self):
        with tempfile.TemporaryDirectory() as tmp:
            story_path = os.path.join(tmp, "main.json")
            with open(story_path, "w", encoding="utf-8") as f:
                json.dump(linear_story({"id": "n1", "type": "wait", "seconds": 1}), f)
            out_lua = os.path.join(tmp, "out.lua")
            r = self.run_cli("build", story_path, "-o", out_lua)
            self.assertEqual(r.returncode, 0, r.stderr)
            with open(out_lua, encoding="utf-8") as f:
                self.assertIn("return node_n1()", f.read())

            mod_dir = os.path.join(tmp, "mymod")
            os.makedirs(os.path.join(mod_dir, "story"))
            with open(os.path.join(mod_dir, "manifest.json"), "w", encoding="utf-8") as f:
                json.dump(MANIFEST, f)
            os.replace(story_path, os.path.join(mod_dir, "story", "main.json"))
            out_pkg = os.path.join(tmp, "mymod.lommod")
            r = self.run_cli("pack", mod_dir, "-o", out_pkg)
            self.assertEqual(r.returncode, 0, r.stderr)
            self.assertTrue(zipfile.is_zipfile(out_pkg))


