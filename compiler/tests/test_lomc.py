def make_story(nodes, story_id="main", start=None, title="测试剧情"):
    """构造合法 story dict 的便捷函数。"""
    return {
        "id": story_id,
        "title": title,
        "start": start or nodes[0]["id"],
        "nodes": nodes,
    }


def linear_story(*extra_nodes):
    """若干节点 + end 结尾的线性好故事。"""
    nodes = list(extra_nodes) + [{"id": "nend", "type": "end"}]
    return make_story(nodes)


def assert_compile_error(testcase, story, *keywords):
    """断言编译抛 LomcError，且消息包含全部关键词。"""
    with testcase.assertRaises(LomcError) as cm:
        compile_story(story)
    msg = str(cm.exception)
    for kw in keywords:
        testcase.assertIn(kw, msg)
    return msg


