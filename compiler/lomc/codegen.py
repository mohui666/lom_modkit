def _emit_cg(node, ctx):
    action, kind = node["action"], node["kind"]
    if action == "hide":
        return ["\t" + _CG_HIDE[kind]]
    fmt, arg_names = _CG_SHOW[kind]
    args = [_lua_value(node[k]) for k in arg_names]
    return ["\t" + fmt % tuple(args)]


