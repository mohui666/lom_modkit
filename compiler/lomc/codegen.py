def lua_str(s):
    """契约 §4 转义：\\ → \\\\，" → \\"，换行 → \\n，\\r → \\r。"""
    return (
        '"'
        + s.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\n", "\\n")
        .replace("\r", "\\r")
        + '"'
    )


def lua_num(n):
    """数值 -> Lua 字面量。整数值不带小数点（与官方脚本风格一致）。"""
    if isinstance(n, bool):
        raise LomcError("内部错误：布尔值不能作为数值 emit")
    if isinstance(n, int):
        return str(n)
    f = float(n)
    if f.is_integer() and abs(f) < 1e15:
        return str(int(f))
    return repr(f)


def _lua_value(v):
    """字符串/数值通用字面量（block.vars 等 value 可为两种类型）。"""
    return lua_str(v) if isinstance(v, str) else lua_num(v)


def _get(char_expr):
    return "characters.Get(%s)" % char_expr


def _portrait(character, portrait):
    return "characters.GetPortrait(%s, %s)" % (character, portrait)


def _say_key(node, ctx):
    """say/death 文本的已读系统 key：MOD_<modid>_<scriptid>_<nodeid>。

    modid 取 ctx["mod_id"]（打包时来自 manifest）；独立 build / 编辑器
    预览没有 mod id 时用 "MOD" 兜底。
    """
    mod_id = ctx.get("mod_id") or "MOD"
    return "MOD_%s_%s_%s" % (mod_id, ctx["script_id"], node["id"])


