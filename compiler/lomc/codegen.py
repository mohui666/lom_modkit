def _emit_branch(node, ctx):
    """分支（契约 §4，两种 source；未命中必须有 else 兜底）。

    ctx["next_id"] 为顺序下一节点 id，作为 else 的默认落点；
    校验已保证需要兜底时 next_id 一定存在。
    """
    source = node.get("source", "mod")
    flag = lua_str(node["flag"])
    next_id = ctx.get("next_id")
    if source == "mod":
        # 按 modflags[flag] 是否已设置二分：value 1=已设置(then)，2=未设置(else)；
        # 缺某一路时该路落顺序下一节点。
        cases = {c["value"]: c["goto"] for c in node["cases"]}
        then_goto = cases.get(1, next_id)
        else_goto = cases.get(2, next_id)
        return [
            "\tif modflags[%s] then" % flag,
            "\t\treturn node_%s()" % then_goto,
            "\telse",
            "\t\treturn node_%s()" % else_goto,
            "\tend",
        ]
    # source="game"：读官方检查点，Switch 找不到时返回 0，else 兜底落顺序下一节点
    lines = ["\tlocal branch1 = checkpointmanager.Switch(%s)" % flag]
    for i, case in enumerate(node["cases"]):
        kw = "if" if i == 0 else "elseif"
        lines.append("\t%s branch1 == %s then" % (kw, lua_num(case["value"])))
        lines.append("\t\treturn node_%s()" % case["goto"])
    lines.append("\telse")
    lines.append("\t\treturn node_%s()" % next_id)
    lines.append("\tend")
    return lines


def _emit_dice(node, ctx):
    """骰子检定：官方五步链 + ResultSelection 三向分支（契约 §4，v1 简化）。

    三向统一取第 1 个 option 的 goto_大成功/成功/失败（契约有歧义，见返回说明）。
    """
    check = lua_str(node["check"])
    first = node["options"][0]
    lines = [
        "\tsetmenudialog(menudialogs.Dice)",
        "\tlocal dice_rand1 = math.random(99)",
        "\tdicemenudialog.SetRandom(99, dice_rand1)",
        "\tlocal dice_result1 = checkpointmanager.Dice(%s, dice_rand1)" % check,
        "\tlocal dice_opts1 = {}",
    ]
    for i, opt in enumerate(node["options"], 1):
        # 契约 §4 菜单项格式："选项一|<33"。游戏把 | 前文本当作本地化 key
        # 解析（DiceOption.UpdateContent → GetStoryText，查不到时原样返回），
        # 分隔符必须保留；文本里的 ASCII 竖线换成全角 "｜" 防格式破坏。
        text = str(opt["text"]).replace("|", "｜")
        entry = "%s|<%s" % (text, lua_num(opt["threshold"]))
        lines.append("\tdice_opts1[%d] = %s" % (i, lua_str(entry)))
    lines += [
        "\tdicemenudialog.Setup(dice_result1.ResultCount, dice_result1.Result, "
        "dice_result1.Header, dice_result1.Additions)",
        "\trunwait(dicemenudialog.ExecuteRoll(dice_opts1, 1, %s))" % check,
        "\tlocal dice_sel1 = dicemenudialog.ResultSelection",
        "\tif dice_sel1 == 1 then",
        "\t\treturn node_%s()" % first["goto_大成功"],
        "\telseif dice_sel1 == 2 then",
        "\t\treturn node_%s()" % first["goto_成功"],
        "\telse",
        "\t\treturn node_%s()" % first["goto_失败"],
        "\tend",
    ]
    return lines


