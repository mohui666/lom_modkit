# 自带流转（分支/跳转/场景切换），story_to_lua 不再追加 return node_<goto>() 行
_NO_FLOW_TYPES = ("end", "choice", "branch", "dice", "goto_scene", "death")


def story_to_lua(story, mod_info=None, source=None):
    """把已校验的 story dict 编译为 Lua 源码字符串。

    mod_info：可选的 manifest dict（pack 时传入），用于文件头注释与
    end 节点 SetNextScript 的 MOD_<modid>_ 前缀。
    source：可选的来源描述（通常是 story/<id>.json），写进文件头注释。
    """
    ctx = {
        "mod_id": mod_info.get("id") if mod_info else None,
        "script_id": story["id"],
        "mood": bool(story.get("mood", False)),
    }
    nodes = story["nodes"]

    lines = [GENERATED_MARK]
    src = source or ("story/%s.json" % story["id"])
    title = story.get("title", "")
    lines.append("-- Source: %s (id=%s, title=%s)" % (src, story["id"], title))
    if mod_info:
        lines.append(
            "-- Mod: %s (%s) v%s by %s"
            % (
                mod_info.get("id", ""),
                mod_info.get("name", ""),
                mod_info.get("version", ""),
                mod_info.get("author", ""),
            )
        )
    lines.append("")

    # 契约 §4：每个脚本开头初始化 mod 内 flag 表（全局表，链式脚本间共享）
    lines.append("-- mod 内剧情 flag 表（不存档，重进游戏清零）")
    lines.append("modflags = modflags or {}")
    # 契约 §4：mood 声明——每个脚本开头声明本脚本心情气泡开关（story 顶层
    # mood 字段，默认 false）；运行时插件注册 mod_set_mood 全局并硬控 ShowMood，
    # 与 mod_hide_mood 双保险防官方情绪面板干扰剧情演出。
    lines.append("mod_set_mood(%s)" % ("true" if ctx["mood"] else "false"))
    lines.append("")

    # 前向声明全部节点函数：Lua 的 local function 无法引用后定义的 local，
    # 而汇合点 / 分支回环要求任意方向的跳转。
    lines.append("-- 节点函数前向声明（支持任意 goto / 分支回环）")
    lines.append("local " + ", ".join("node_%s" % n["id"] for n in nodes))
    lines.append("")

    for i, node in enumerate(nodes):
        lines.append("-- [%s] %s" % (node["id"], node["type"]))
        lines.append("node_%s = function()" % node["id"])
        emitter = _EMITTERS.get(node["type"])
        if emitter is None:
            raise LomcError(
                '内部错误：节点 "%s" 类型 "%s" 未校验通过' % (node["id"], node["type"])
            )
        # branch 的 else 兜底需要顺序下一节点 id（校验已保证需要时存在）
        ctx["next_id"] = nodes[i + 1]["id"] if i + 1 < len(nodes) else None
        lines.extend(emitter(node, ctx))
        if node["type"] not in _NO_FLOW_TYPES:
            # 显式 goto 覆盖顺序流（契约 §3）；校验已保证目标存在
            goto = node.get("goto")
            if goto is None:
                goto = nodes[i + 1]["id"]
            lines.append("\treturn node_%s()" % goto)
        lines.append("end")
        lines.append("")

    lines.append("return node_%s()" % story["start"])
    return "\n".join(lines) + "\n"
