def _emit_say(node, ctx):
    mode = node.get("mode", "character")
    # 已读系统：文本不再裸字面量，改发射 key 查表（官方已读变黄/可快进机制）；
    # 文本本体进包内 texts.json，由运行时插件注册进 LeanLocalization。
    say_call = "\tsay(luamanager.GetStoryText(%s))" % lua_str(_say_key(node, ctx))
    hide_mood = "\tmod_hide_mood()" if not ctx.get("mood", False) else None

    def _with_mood(seq):
        # 心情气泡：story mood 关闭时 say 前/后各隐藏一次（发言会触发情绪面板）
        out = []
        for item in seq:
            if item == say_call:
                if hide_mood:
                    out.append(hide_mood)
                out.append(item)
                if hide_mood:
                    out.append(hide_mood)
            else:
                out.append(item)
        return out

    if mode in ("narrative", "center"):
        # 旁白/居中旁白：忽略 character（契约 §4）。
        # 官方实证：任何 say 前都要设 sayoptions（ch1_1 的 center 旁白同样如此），
        # 否则等待输入/淡出行为取决于环境默认值。
        return _with_mood(
            [
                "\tsetsaydialog(saydialogs.%s)" % mode,
                "\tsayoptions.waitforinput = true",
                "\tsayoptions.fadewhendone  = true",
                "\tsetcharacter(narrative)",
                say_call,
            ]
        )

    c = lua_str(node["character"])
    portrait = lua_str(node.get("portrait", "normal"))
    lines = [
        "\tsetsaydialog(saydialogs.%s)" % mode,
        # 表情差分：先加载该表情的立绘差分（官方 93% say 块均如此；
        # 不加载则台上人物立绘不换，只有气泡变）
        "\tcharacters.LoadCharacterPortrait(%s, %s)" % (c, portrait),
        "\tsayoptions.waitforinput = true",
        "\tsayoptions.fadewhendone  = true",
        "\tstage.showPortrait(%s, %s)" % (_get(c), _portrait(c, portrait)),
        "\tsetcharacter(%s, %s)" % (_get(c), _portrait(c, portrait)),
    ]
    if mode == "think":
        # 内心独白：say 前开独白遮罩，say 后关闭（契约 §4）
        lines.append("\tos_mask.SetLastPosition()")
        lines.append("\tos_mask.Show(true)")
    lines.append("\tcharacters.Focus(%s)" % c)
    lines.append(say_call)
    if mode == "think":
        lines.append("\tos_mask.Show(false)")
    return _with_mood(lines)


def _emit_choice(node, ctx):
    # 局部变量名固定 option1/choice1：每个节点一个独立函数，不会冲突
    dialog = node.get("dialog", "Options")  # §3.3 皮肤
    lines = [
        "\tsetmenudialog(menudialogs.%s)" % dialog,
        "\tlocal option1 = {}",
    ]
    for i, opt in enumerate(node["options"], 1):
        lines.append("\toption1[%d] = %s" % (i, lua_str(opt["text"])))
    lines.append("\tlocal choice1 = choose(option1)")
    lines.append("\tmenudialogs.%s.SetActive(false)" % dialog)
    for i, opt in enumerate(node["options"], 1):
        kw = "if" if i == 1 else "elseif"
        lines.append("\t%s choice1 == %d then" % (kw, i))
        lines.append("\t\treturn node_%s()" % opt["goto"])
    lines.append("\tend")
    return lines


