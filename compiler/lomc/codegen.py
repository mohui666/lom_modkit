def _emit_music(node, ctx):
    op = node.get("op", "play")
    if op == "stop":
        return ["\tluamanager.StopMusic()"]
    if op == "fadeout":
        return ["\tluamanager.FadeOutMusic(%s)" % lua_num(node.get("seconds", 2))]
    return ["\tluamanager.PlayMusic(%s)" % lua_str(node["name"])]


def _emit_sound(node, ctx):
    kind = node.get("kind", "sound")
    op = node.get("op", "play")
    if op == "fadeout":  # 校验已保证 kind="env"
        return ["\tluamanager.FadeOutEnvSound(%s)" % lua_num(node.get("seconds", 1))]
    if kind == "env":
        return ["\tluamanager.PlayEnvSound(%s)" % lua_str(node["name"])]
    return ["\tluamanager.PlaySound(%s)" % lua_str(node["name"])]


def _emit_scene(node, ctx):
    view = node["view"]
    lines = ['\trunblock(flowcharts.view, "out")']
    if view != "out":  # view="out" 时只淡出；"black"/"white" 为纯色，照常 emit
        lines.append('\tgetvar(flowcharts.view, "ViewName").value = %s' % lua_str(view))
        lines.append('\trunblock(flowcharts.view, "view")')
    return lines


def _emit_show(node, ctx):
    c = lua_str(node["character"])
    portrait = lua_str(node.get("portrait", "normal"))
    facing = lua_str(node.get("facing", "right"))
    pos = lua_str(node["position"])
    fade = lua_num(node.get("fadeDuration", 0))
    move = lua_num(node.get("moveDuration", 0))
    return [
        "\trunwait(characters.LoadCharacterAsset(%s))" % c,
        "\tstage.show{character=%s, portrait=%s, fromPosition=%s, toPosition=%s, "
        "facing=%s, fadeDuration=%s, moveDuration=%s, useDefaultSettings=false}"
        % (_get(c), _portrait(c, portrait), pos, pos, facing, fade, move),
        "\tcharacters.Focus(%s)" % c,
    ]


