"""story.json -> 游戏原生 Lua 代码生成（契约 v3 §4）。

- 每个节点编译为 node_<id>() 函数；文件头前向声明
  `local node_n1, node_n2, ...`，然后 `node_nX = function() ... end`；
  流转用尾调用 `return node_<goto>()`；顶层 `return node_<start>()`。
- 脚本开头 emit `modflags = modflags or {}`（mod 内 flag 表）。
- 各节点 emit 范式逐条对应契约 §4（官方脚本实证，raw_scripts/ 可参考）。
- choice/branch/dice/end/goto_scene 自带流转，不追加顺序/goto 行；
  其余节点末尾追加 return node_<goto 或顺序下一节点>()。
"""

from .errors import LomcError

GENERATED_MARK = "-- Generated by lomc, do not edit"


def lua_str(s):
    """契约 §4 转义：\\ → \\\\，" → \\"，换行 → \\n，\\r → \\r。"""
    return (
        '"'
        + s.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\n", "\\n")
        .replace("\r", "\\r")
        + '"'
    )


def lua_num(n):
    """数值 -> Lua 字面量。整数值不带小数点（与官方脚本风格一致）。"""
    if isinstance(n, bool):
        raise LomcError("内部错误：布尔值不能作为数值 emit")
    if isinstance(n, int):
        return str(n)
    f = float(n)
    if f.is_integer() and abs(f) < 1e15:
        return str(int(f))
    return repr(f)


def _lua_value(v):
    """字符串/数值通用字面量（block.vars 等 value 可为两种类型）。"""
    return lua_str(v) if isinstance(v, str) else lua_num(v)


def _get(char_expr):
    return "characters.Get(%s)" % char_expr


def _portrait(character, portrait):
    return "characters.GetPortrait(%s, %s)" % (character, portrait)


