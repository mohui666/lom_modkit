def _emit_branch(node, ctx):
    """分支（契约 §4，五种 source；未命中必须有 else 兜底）。

    ctx["next_id"] 为顺序下一节点 id，作为 else 的默认落点；
    校验已保证需要兜底时 next_id 一定存在。
    """
    source = node.get("source", "mod")
    flag = lua_str(node["flag"]) if "flag" in node else None
    next_id = ctx.get("next_id")
    if source == "mod":
        # 按 modflags[flag] 是否已设置二分：value 1=已设置(then)，2=未设置(else)；
        # 缺某一路时该路落顺序下一节点。
        cases = {c["value"]: c["goto"] for c in node["cases"]}
        then_goto = cases.get(1, next_id)
        else_goto = cases.get(2, next_id)
        return [
            "\tif modflags[%s] then" % flag,
            "\t\treturn node_%s()" % then_goto,
            "\telse",
            "\t\treturn node_%s()" % else_goto,
            "\tend",
        ]
    if source == "condition":
        # 官方条件检查点：checkpointmanager.Condition(flag) 返回 bool；
        # value 1=真(then)，2=假(else)，缺某一路时该路落顺序下一节点。
        cases = {c["value"]: c["goto"] for c in node["cases"]}
        then_goto = cases.get(1, next_id)
        else_goto = cases.get(2, next_id)
        return [
            "\tif checkpointmanager.Condition(%s) then" % flag,
            "\t\treturn node_%s()" % then_goto,
            "\telse",
            "\t\treturn node_%s()" % else_goto,
            "\tend",
        ]
    if source == "stat":
        # 主角属性数值分支：GetStatData(stat, 1)（sign=1 取正值）；
        # 按 case 的 op/value 逐项比较，未命中 else 兜底。
        lines = [
            "\tlocal branch1 = luamanager.GetStatData(%s, 1)" % lua_str(node["stat"])
        ]
        for i, case in enumerate(node["cases"]):
            kw = "if" if i == 0 else "elseif"
            lines.append(
                "\t%s branch1 %s %s then"
                % (kw, case.get("op", ">="), lua_num(case["value"]))
            )
            lines.append("\t\treturn node_%s()" % case["goto"])
        lines.append("\telse")
        lines.append("\t\treturn node_%s()" % next_id)
        lines.append("\tend")
        return lines
    if source == "flag_value":
        # 官方任务旗标数值分支：tonumber(GetFlagData(flag)) + 同 stat 的比较
        lines = ["\tlocal branch1 = tonumber(luamanager.GetFlagData(%s))" % flag]
        for i, case in enumerate(node["cases"]):
            kw = "if" if i == 0 else "elseif"
            lines.append(
                "\t%s branch1 %s %s then"
                % (kw, case.get("op", ">="), lua_num(case["value"]))
            )
            lines.append("\t\treturn node_%s()" % case["goto"])
        lines.append("\telse")
        lines.append("\t\treturn node_%s()" % next_id)
        lines.append("\tend")
        return lines
    # source="game"：读官方检查点，Switch 找不到时返回 0，else 兜底落顺序下一节点
    lines = ["\tlocal branch1 = checkpointmanager.Switch(%s)" % flag]
    for i, case in enumerate(node["cases"]):
        kw = "if" if i == 0 else "elseif"
        lines.append("\t%s branch1 == %s then" % (kw, lua_num(case["value"])))
        lines.append("\t\treturn node_%s()" % case["goto"])
    lines.append("\telse")
    lines.append("\t\treturn node_%s()" % next_id)
    lines.append("\tend")
    return lines


def _band_rank(bands):
    """结果带质量排名：返回每个带的名次 1..N（最差→最好）。

    检查点的结果带顺序不保证是差→好（官方有 34 个倒序检查点，如
    ['>80', '>40', '<=40']），因此按条件文本的数值推断质量：
    数值越大越好；同数值时 '>'/'>=/'=' 优于 '<'/'<='（更窄的顶带）。
    解析不了条件的带按展示顺序兜底。
    """
    import re as _re

    parsed = []
    for b in bands:
        m = _re.search(r"(<=|>=|<|>|=)\s*(\d+)", str(b.get("cond", "")))
        if m:
            op, num = m.group(1), int(m.group(2))
            parsed.append((num, op in (">", ">=", "=")))
        else:
            parsed.append(None)
    if not any(p is not None for p in parsed):
        return list(range(1, len(bands) + 1))
    order = sorted(
        range(len(bands)),
        key=lambda i: (
            parsed[i][0] if parsed[i] is not None else -1,
            parsed[i][1] if parsed[i] is not None else False,
        ),
    )
    ranks = [0] * len(bands)
    for rank, i in enumerate(order, 1):
        ranks[i] = rank
    return ranks


def _emit_dice(node, ctx):
    """骰子检定：按检查点官方元数据发射（骰子范围、结果带条数与文本）。

    官方实证（travel_result_601_101 / ch6_8_2_break_start_01 等）：骰子菜单
    按结果带索引选项按钮（UpdateSelection 用 ResultSelection-1 做下标），
    选项条数必须 >= 结果带数，否则越界 NRE、菜单卡死（继续按钮永不出现）。
    选项按官方提取顺序发射（菜单高亮按此索引），分支按带的质量名次映射：
    最差带→goto_失败；3 带及以上时最优带→goto_大成功、中间带→goto_成功；
    2 带时最优带→goto_成功（无独立大成功档）。

    options[0]["band_texts"]（可选，列表）：逐带覆写选项文本（作者自定义
    文本字面量，游戏 GetStoryText 查不到 key 时原样显示，无需进 texts.json）；
    缺省时用官方结果带文本。条件部分永远用官方元数据。
    """
    check = node["check"]
    meta = get_dice_meta(check) or {}
    bands = meta.get("bands") or [
        {"text": str(node["options"][0].get("text", "")), "cond": ""}
    ]
    dice_max = meta.get("max", 99)
    opt = node["options"][0]
    band_texts = opt.get("band_texts")
    lines = [
        "	setmenudialog(menudialogs.Dice)",
        "	local dice_rand1 = math.random(%d)" % dice_max,
        "	dicemenudialog.SetRandom(%d, dice_rand1)" % dice_max,
        "	local dice_result1 = checkpointmanager.Dice(%s, dice_rand1)"
        % lua_str(check),
        "	local dice_opts1 = {}",
    ]
    for i, band in enumerate(bands, 1):
        # 文本会被游戏当本地化 key 解析（GetStoryText 查不到时原样返回）；
        # ASCII | 换成全角｜防分隔符冲突（条件部分紧随其后）
        if isinstance(band_texts, list) and len(band_texts) == len(bands):
            text = str(band_texts[i - 1]).replace("|", "｜")
        else:
            text = str(band.get("text", "")).replace("|", "｜")
        entry = "%s|%s" % (text, band.get("cond", ""))
        lines.append("	dice_opts1[%d] = %s" % (i, lua_str(entry)))
    lines += [
        "	dicemenudialog.Setup(dice_result1.ResultCount, dice_result1.Result, "
        "dice_result1.Header, dice_result1.Additions)",
        "	runwait(dicemenudialog.ExecuteRoll(dice_opts1, 1, %s))" % lua_str(check),
        "	local dice_sel1 = dicemenudialog.ResultSelection",
    ]
    n = len(bands)
    ranks = _band_rank(bands)

    def goto_for_rank(r):
        if r == 1:
            return opt["goto_失败"]
        if r == n and n >= 3:
            return opt["goto_大成功"]
        return opt["goto_成功"]

    if n == 2:
        lines += [
            "	if dice_sel1 == 1 then",
            "		return node_%s()" % goto_for_rank(ranks[0]),
            "	else",
            "		return node_%s()" % goto_for_rank(ranks[1]),
            "	end",
        ]
    else:
        lines.append("	if dice_sel1 == 1 then")
        lines.append("		return node_%s()" % goto_for_rank(ranks[0]))
        for i in range(1, n - 1):
            lines.append("	elseif dice_sel1 == %d then" % (i + 1))
            lines.append("		return node_%s()" % goto_for_rank(ranks[i]))
        lines.append("	else")
        lines.append("		return node_%s()" % goto_for_rank(ranks[n - 1]))
        lines.append("	end")
    return lines


def _emit_goto_scene(node, ctx):
    lines = []
    # End 不是跳进简化 End 场景：原版真正的“汗青书结局卡”流程是
    # endgamepanel.Open(key) -> 玩家确认 -> 黑幕 -> Title。运行时 patch 在官方
    # EndGamePanel 第一次 yield 前写入 mod 标题/正文/插图，因此完整复用官方版式、
    # 渐显和确认输入。原版所有 EndGamePanel 结局在玩家确认后都回 Title；旧格式的
    # next 字段继续允许读取，但不再制造一个游戏本身不存在的自定义返回去向。
    if node["scene"] == "End" and "image" in node:
        lines.append(
            "\tmod_set_ending_text(%s, %s, %s)"
            % (
                lua_str(node.get("title", "")),
                lua_str(node.get("desc", "")),
                lua_str(node["image"]),
            )
        )
    elif node["scene"] == "End" and ("title" in node or "desc" in node):
        lines.append(
            "\tmod_set_ending_text(%s, %s)"
            % (lua_str(node.get("title", "")), lua_str(node.get("desc", "")))
        )
    elif node["scene"] == "GameOver" and ("title" in node or "desc" in node):
        # GameOver 使用死亡覆盖通道，避免把 EndingRequested/结局图片状态带进
        # 死亡场景；显示布局仍由同一个官方 GameOverController patch 完成。
        lines.append(
            "\tmod_set_death_text(%s, %s)"
            % (lua_str(node.get("title", "")), lua_str(node.get("desc", "")))
        )
    if node["scene"] == "End":
        has_mod_content = any(
            isinstance(node.get(name), str) and node[name].strip()
            for name in ("title", "desc", "image")
        )
        panel_key = "__MORTAL_MOD_END__" if has_mod_content else node.get("key", "")
        lines += [
            "\tluamanager.SetEnableActions(0)",
            "\trunwait(endgamepanel.Open(%s))" % lua_str(panel_key),
            "\tluamanager.SetEnableActions(1)",
            '\trunwait(transitionblack.TransitionIn("lr"))',
            '\tluamanager.ChangeScene("Title", "", "")',
        ]
        return lines
    next_scene = "Title" if node["scene"] == "GameOver" else node.get("next", "Story")
    lines.append(
        "\tluamanager.ChangeScene(%s, %s, %s)"
        % (
            lua_str(node["scene"]),
            lua_str(node.get("key", "")),
            lua_str(next_scene),
        )
    )
    return lines


def _emit_panel(node, ctx):
    p = node["panel"]
    if p == "martial":
        return ["\trunwait(martialpanel.Open(%s))" % lua_num(node.get("mode", 0))]
    if p == "weapon":
        return ["\trunwait(weaponupgradepanel.Open())"]
    if p == "poison":
        return ["\trunwait(poisonupgradepanel.Open())"]
    if p == "cg":
        return ["\trunwait(cgpanel.Open(%s))" % lua_str(node["key"])]
    if p == "cgvideo":
        return ["\trunwait(cgvideopanel.Open(%s, 0))" % lua_str(node["key"])]
    if p == "shop":
        return ["\trunwait(shoppanel.Open(%s))" % lua_num(node.get("discount", 0))]
    if p == "newshop":  # 契约 §3.1：除 newshop 外均 runwait
        return ["\tshoppanel.NewShop()"]
    if p == "credit":
        return ["\trunwait(creditpanel.Open())"]
    # endgame
    return ["\trunwait(endgamepanel.Open(%s))" % lua_str(node["key"])]


def _emit_wait(node, ctx):
    return ["\twait(%s)" % lua_num(node["seconds"])]


def _emit_end(node, ctx):
    next_script = node.get("next_script")
    if next_script is None:
        # 无 next_script：官方标准收尾，返回自由模式（契约 §3.1）。
        # 注意不能 emit luamanager.Init()：无后续脚本时 Init 会重跑当前
        # 脚本，造成死循环。
        return ['\tluamanager.ChangeScene("Free", "", "")']
    # 有 next_script：链到同包内另一脚本。运行时注册名带 MOD_<modid>_
    # 前缀（契约 §3.1/§6）；裸 build 不知 mod id 时退化为原始脚本 id。
    target = (
        "MOD_%s_%s" % (ctx["mod_id"], next_script) if ctx.get("mod_id") else next_script
    )
    return [
        "\tluamanager.SetNextScript(%s)" % lua_str(target),
        "\tluamanager.Init()",
    ]


def _emit_death(node, ctx):
    """死亡文本节点：黑屏过渡 → mod_set_death_text(title, text) → 官方 GameOver 死亡画面。

    自定死亡文本两段式：短标题（缺省「勝敗乃兵家常事」）+ 多行描述，均 lua_str
    字面量（不进 texts.json / 已读系统）；运行时插件 patch GameOverController
    把两段文本显示在官方死亡画面中央（标题栏 + 黑底红字 + 返回按钮，契约 §6）。
    death_id 必须是 ≥900000 的 mod 专属 id：官方 GameOver 场景用 id 查
    LibrarySystem 并解锁/记录官方结局，mod 专属 id 查不到 → 无副作用，但
    死亡画面本身照常显示（校验见 validate.py）。
    """
    title = node.get("title") or "勝敗乃兵家常事"
    return [
        '\trunblock(flowcharts.view, "out")',
        '\tgetvar(flowcharts.view, "ViewName").value = "black"',
        '\trunblock(flowcharts.view, "view")',
        "\tmod_set_death_text(%s, %s)" % (lua_str(title), lua_str(node["text"])),
        "\tluamanager.ChangeScene(%s, %s, %s)"
        % (
            lua_str("GameOver"),
            lua_str(node["death_id"]),
            # 原版 GameOverController 的按钮固定为读档 / Title，不读取
            # CurrentNextScene；统一写 Title，避免生成看似可配置但实际无效的数据。
            lua_str("Title"),
        ),
    ]


